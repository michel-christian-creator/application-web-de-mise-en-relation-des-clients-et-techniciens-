export function tr(lang: Lang, key: string): string {
  if (lang === "fr") return key
  return EN_DICT[key] ?? key
}

export function localeOf(lang: Lang): string {
  return lang === "en" ? "en-GB" : "fr-FR"
}

export function tKey(lang: Lang, key: string): string {
  return tr(lang, key)
}

type I18nContextType = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: string) => string
  locale: string
}

const I18nContext = createContext<I18nContextType | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return localStorage.getItem("mboaTechLang") === "en" ? "en" : "fr"
    } catch {
      return "fr"
    }
  })

  useEffect(() => {
    try {
      localStorage.setItem("mboaTechLang", lang)
      document.documentElement.lang = lang
    } catch {
      // stockage indisponible : on ignore
    }
  }, [lang])

  const t = useCallback((key: string) => tr(lang, key), [lang])
  const value: I18nContextType = { lang, setLang, t, locale: localeOf(lang) }

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextType {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error("useI18n doit être utilisé à l'intérieur de <I18nProvider>")
  }
  return ctx
}
